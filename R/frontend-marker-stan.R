# Reporting failures do not change the effective-loading likelihood or drop draws.
.bh_marker_generated <- function()list(
  declarations=c(
    "matrix[J,J] Sigma_common=effective_loadings*R_component*transpose(effective_loadings);",
    "matrix[J,J] Sigma_parameter=D_parameter*R_parameter*transpose(D_parameter);",
    "matrix[J,J] Sigma_predictor=Sigma_common+Sigma_parameter;",
    "array[J,J] int<lower=0,upper=1> Sigma_common_available;",
    "array[J,J] int<lower=0,upper=1> Sigma_parameter_available;",
    "array[J,J] int<lower=0,upper=1> Sigma_predictor_available;",
    "vector[K] log_component_row_sd=log(component_row_sd);",
    "matrix[K,K] component_covariance;","matrix[K,K] component_covariance_log_abs;",
    "array[K,K] int<lower=0,upper=1> component_covariance_available;",
    "matrix[K,N] f;","matrix[K,N] f_log_abs;","array[K,N] int<lower=0,upper=1> f_available;"),
  statements=c(
    "if(K>0) for(k in 1:K) {",
    "  for(n in 1:N) {",
    "    real value=component_row_sd[k]*z[k,n];",
    "    f_log_abs[k,n]=log_component_row_sd[k]+log(abs(z[k,n]));",
    "    f_available[k,n]=!(is_nan(value)||is_inf(value)||(z[k,n]!=0 && value==0));",
    "    f[k,n]=f_available[k,n] ? value : not_a_number();",
    "  }",
    "  for(l in 1:K) {",
    "    real value;",
    "    component_covariance_log_abs[k,l]=log(abs(R_component[k,l]))+log_component_row_sd[k]+log_component_row_sd[l];",
    "    value=(R_component[k,l]<0 ? -1.0 : (R_component[k,l]>0 ? 1.0 : 0.0))*exp(component_covariance_log_abs[k,l]);",
    "    component_covariance_available[k,l]=!(is_nan(value)||is_inf(value)||(R_component[k,l]!=0 && value==0));",
    "    component_covariance[k,l]=component_covariance_available[k,l] ? value : not_a_number();",
    "  }",
    "}",
    "if(J>0) for(j in 1:J) {",
    "  int common_active=0; int parameter_active=0;",
    "  if(K>0) common_active=max(abs(effective_loadings[j]))>0;",
    "  if(U>0) parameter_active=max(abs(D_parameter[j]))>0;",
    "  for(l in 1:J) {",
    "    Sigma_common_available[j,l]=!(is_nan(Sigma_common[j,l])||is_inf(Sigma_common[j,l])||(j==l && common_active && Sigma_common[j,l]<=0));",
    "    Sigma_parameter_available[j,l]=!(is_nan(Sigma_parameter[j,l])||is_inf(Sigma_parameter[j,l])||(j==l && parameter_active && Sigma_parameter[j,l]<=0));",
    "    Sigma_predictor_available[j,l]=!(is_nan(Sigma_predictor[j,l])||is_inf(Sigma_predictor[j,l])||(j==l && (common_active||parameter_active) && Sigma_predictor[j,l]<=0));",
    "    if(!Sigma_common_available[j,l]) Sigma_common[j,l]=not_a_number();",
    "    if(!Sigma_parameter_available[j,l]) Sigma_parameter[j,l]=not_a_number();",
    "    if(!Sigma_predictor_available[j,l]) Sigma_predictor[j,l]=not_a_number();",
    "  }",
    "}"))
