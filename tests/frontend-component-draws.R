root<-Sys.getenv('MEASUREMENTPKG_SOURCE')
if(nzchar(root))for(f in list.files(file.path(root,'R'),pattern='[.]R$',full.names=TRUE))source(f)else library(bmeas)
pvt<-function(n)if(nzchar(root))get(n,.GlobalEnv)else getFromNamespace(n,'bmeas')
local({
 ok<-function(x,label){stopifnot(isTRUE(x));cat('PASS',label,'\n')}
 err<-function(action,code){e<-tryCatch(action(),error=identity);ok(inherits(e,'measurement_error')&&identical(e$code,code),code)}
 precision<-pvt('.bh_component_precision')
 p<-precision(data.frame(chain_id=c(2L,9L),sig_figs=c(12,17)),list())
 ok(identical(p$sig_figs,c(12,17)),'mixed precision stays per chain')
 unknown<-data.frame(chain_id=c(2L,9L),sig_figs=c(NA,-1))
 ok(all(is.na(precision(unknown,list())$sig_figs)),'unknown precision stays unknown')
 err(function()precision(unknown,list(run=17L)),'E_COMPONENT_PRECISION')
 ok(pvt('.bh_run_csv_sig_figs')()==17L,'new fit default17')
 for(p in c(1L,12L,18L))ok(pvt('.bh_run_csv_sig_figs')(list(csv_sig_figs=p))==p,'explicit precision retained')
 err(function()pvt('.bh_run_csv_sig_figs')(list(csv_sig_figs=19)),'E_RUN_CONFIG')
 rules<-list(constants=matrix(NA_real_,2,2),representative=matrix(0L,2,2))
 check<-pvt('.bh_component_matrix');bad<-matrix(c(1,2,2,1),2);s<-check(bad,17,rules,2)
 ok(s$range=='outside_correlation_range'&&s$positive_definite=='not_positive_definite_at_saved_precision','invalid matrix reported without repair')
 bad[1,2]<-.2;ok(check(bad,17,rules,2)$positive_definite=='not_assessed_nonexact_symmetry','asymmetric matrix not factorized')
 ok(check(diag(2),NA_real_,rules,2)$diagonal=='not_assessed_unknown_precision','unknown precision has no envelope verdict')
 cap<-list(max_output_values=66,max_matrix_work=120,context=list(max_context_bytes=2^20,max_context_nodes=100000,max_depth=64))
 ledger<-pvt('.bh_component_ledger')(cap$context)
 coords<-data.frame(index=1:2,id=c('coordinate:A','coordinate:B'),display=c('A','B'))
 plan<-list(K=2,square=4,V=10,W=33,matrix_work=60,budget=cap,portable=FALSE,rules=rules,
  metadata=list(tables=list(coordinates=coords),prior=list(),upstream=list(),source_context=list(recorded_precision=list(run=NULL,provenance=NULL))))
 acquired<-list(draws=rbind(c(1,.5,.5,1,2,3,1,0,1,1),c(1,0,0,1,1e200,1e200,1,1,1,1)),
  draw_keys=data.frame(chain_id=c(7L,7L),saved_row=1:2),receipt=list(sources=data.frame(chain_id=7L,sig_figs=17)))
 x<-pvt('.bh_component_result')(plan,acquired,ledger,NULL)
 ok(identical(x$draw_keys,acquired$draw_keys)&&identical(unname(x$correlation[1,,]),matrix(c(1,.5,.5,1),2)),'saved matrix and keys authoritative')
 ok(abs(x$covariance[1,1,2]-3)<1e-12&&is.nan(x$covariance[1,2,1])&&x$derived_available[1,2,1]&&!x$original_available[1,2,1],'original unavailable flag remains distinct')
 ok(is.nan(x$covariance[2,1,1])&&!x$derived_available[2,1,1]&&is.finite(x$log_abs_covariance[2,1,1]),'overflow retains log evidence')
 ok(x$covariance[2,1,2]==0&&x$log_abs_covariance[2,1,2]==-Inf&&x$derived_available[2,1,2],'represented zero stays available')
 ok(identical(dimnames(x$correlation),list(NULL,coords$id,coords$id)),'coordinate axes and draw keys separate')
 path<-tempfile(fileext='.rds');on.exit(unlink(path),add=TRUE);saveRDS(x,path)
 ok(identical(readRDS(path),x),'plain extracted data roundtrip')
 cat('PASSED component helper regressions; no acquisition, fitting or native compilation\n')
})
